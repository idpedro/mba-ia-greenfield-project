import type { INestApplication } from '@nestjs/common';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import { ApiErrorEnvelope } from '../common/openapi/api-error-envelope.dto';
import pluginMetadata from '../metadata';

export function buildSwaggerConfig() {
  return new DocumentBuilder()
    .setTitle('StreamTube API')
    .setDescription('API REST do StreamTube')
    .setVersion('1.0')
    .addBearerAuth(
      { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
      'access-token',
    )
    .build();
}

// Loads the @nestjs/swagger CLI plugin metadata (src/metadata.ts, generated by
// `npm run openapi:metadata`) so the document is complete even when the code
// was not compiled with the plugin (ts-node export, ts-jest tests).
export async function buildSwaggerDocument(app: INestApplication) {
  await SwaggerModule.loadPluginMetadata(pluginMetadata);
  return SwaggerModule.createDocument(app, buildSwaggerConfig(), {
    extraModels: [ApiErrorEnvelope],
  });
}
